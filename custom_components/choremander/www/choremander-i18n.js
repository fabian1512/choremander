  function normalize(lang) {
    if (!lang) return "en";
    var l = String(lang).toLowerCase();
    if (l.indexOf("de") === 0) return "de";
    return "en";
  }

  function lookup(dict, key) {
    var parts = key.split(".");
    var node = dict;
    for (var i = 0; i < parts.length; i++) {
      if (node == null || typeof node !== "object") return undefined;
      node = node[parts[i]];
    }
    return node;
  }

  var currentLanguage = normalize(
    (typeof navigator !== "undefined" && navigator.language) || "en"
  );

  function t(key, vars, lang) {
    var dict = dictionaries[normalize(lang || currentLanguage)] || dictionaries.en;
    var value = lookup(dict, key);
    if (value == null) value = lookup(dictionaries.en, key);
    if (value == null) return key;
    if (vars && typeof value === "string") {
      for (var name in vars) {
        if (Object.prototype.hasOwnProperty.call(vars, name)) {
          value = value.split("{" + name + "}").join(String(vars[name]));
        }
      }
    }
    return value;
  }

  window.ChoremanderI18n = {
    t: t,
    setLanguage: function (lang) {
      currentLanguage = normalize(lang);
    },
    get language() {
      return currentLanguage;
    },
    dictionaries: dictionaries,
  };
